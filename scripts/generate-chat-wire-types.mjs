#!/usr/bin/env node
// Generates the frontend's chat wire types from the tinychannels web wire
// schema (vendor/tinychannels, `WebChannelEvent`). The schema is the single
// source of truth: do not hand-write mirrors of these types.
//
//   node scripts/generate-chat-wire-types.mjs          write the file
//   node scripts/generate-chat-wire-types.mjs --check  fail if it is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import { createRequire } from 'node:module';

const prettier = createRequire(resolve(dirname(fileURLToPath(import.meta.url)), '../app/package.json'))('prettier');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(
  root,
  'vendor/tinychannels/crates/tinychannels-bus/schema/web-channel-event.schema.json'
);
const outPath = resolve(root, 'app/src/services/chatWire.generated.ts');

export async function render() {
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
  const body = await compile(schema, 'WebChannelEvent', {
    bannerComment: '',
    additionalProperties: false,
    unknownAny: false,
    format: false,
    style: { singleQuote: true },
  });
  const text =
    '/* eslint-disable */\n' +
    '// @generated by scripts/generate-chat-wire-types.mjs from\n' +
    '// vendor/tinychannels/crates/tinychannels-bus/schema/web-channel-event.schema.json.\n' +
    '// Do not edit by hand; run `pnpm chat-wire:generate`.\n\n' +
    body;
  // Fixed options (not the repo config) so the output is stable; the file is
  // listed in .prettierignore.
  return prettier.format(text, { parser: 'typescript', singleQuote: true, printWidth: 100 });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (!existsSync(schemaPath)) {
    console.error(`schema not found: ${schemaPath} (init submodules)`);
    process.exit(2);
  }
  const next = await render();
  if (process.argv.includes('--check')) {
    const cur = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
    if (cur !== next) {
      console.error('chatWire.generated.ts is stale; run `pnpm chat-wire:generate`');
      process.exit(1);
    }
    console.log('chatWire.generated.ts is current');
  } else {
    writeFileSync(outPath, next);
    console.log(`wrote ${outPath}`);
  }
}
