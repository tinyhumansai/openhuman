/// The primary (index 0) account of each chain and its derivation path.
pub(crate) const PRIMARY_ACCOUNTS: [(WalletChain, &str); 4] = [
    (WalletChain::Evm, "m/44'/60'/0'/0/0"),
    (WalletChain::Btc, "m/44'/0'/0'/0/0"),
    (WalletChain::Solana, "m/44'/501'/0'/0'"),
    (WalletChain::Tron, "m/44'/195'/0'/0/0"),
];

/// A secondary account derived from the same recovery phrase as the primary
/// accounts. It never signs module transfers; it signs only host-built
/// transactions through `wallet.execute_prepared_program`, under its own
/// `[wallet_policy.accounts.<chain>_<index>]` section.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct SecondaryAccount {
    pub chain: WalletChain,
    pub index: u32,
    pub derivation_path: &'static str,
    pub label: &'static str,
}

/// Every secondary account the host knows how to derive. Recovery and import
/// derive them all; a wallet set up before an entry existed derives it on
/// first use ([`ensure_account`]).
///
/// Solana index 1 follows the account-index convention Phantom and
/// `solana-keygen` use (`m/44'/501'/<index>'/0'`).
pub(crate) const SECONDARY_ACCOUNTS: [SecondaryAccount; 1] = [SecondaryAccount {
    chain: WalletChain::Solana,
    index: 1,
    derivation_path: "m/44'/501'/1'/0'",
    label: "giveaway",
}];

/// The canonical derivation path of `chain`'s account `index`, if the host
/// knows that account.
pub(crate) fn account_derivation_path(chain: WalletChain, index: u32) -> Option<&'static str> {
    if index == 0 {
        return PRIMARY_ACCOUNTS
            .iter()
            .find(|(candidate, _)| *candidate == chain)
            .map(|(_, path)| *path);
    }
    secondary_account(chain, index).map(|account| account.derivation_path)
}

fn secondary_account(chain: WalletChain, index: u32) -> Option<&'static SecondaryAccount> {
    SECONDARY_ACCOUNTS
        .iter()
        .find(|account| account.chain == chain && account.index == index)
}

fn supported_word_counts() -> String {
    tinywallet_bus::MNEMONIC_WORD_COUNTS
        .iter()
        .map(u8::to_string)
        .collect::<Vec<_>>()
        .join(", ")
}

/// Generate recovery material through the attested wallet module.
pub async fn generate_recovery_phrase(
    ctx: &DispatchCtx,
    word_count: u8,
) -> Result<Outcome<GeneratedRecoveryPhrase>, String> {
    tinywallet_bus::validate_mnemonic_word_count(word_count).map_err(|error| error.to_string())?;
    let config = ctx.load_config().await?;
    let generated = crate::modules::wallet::generate_mnemonic(&config, word_count)
        .await
        .map_err(|error| error.to_string())?;
    Ok(Outcome::new(
        GeneratedRecoveryPhrase {
            phrase: generated.phrase,
            word_count: generated.word_count,
        },
        vec!["recovery phrase generated by wallet module".to_string()],
    ))
}

/// Validate a phrase and derive the public setup facts inside TinyWallet.
///
/// The returned BIP-39 seed is used only for OpenHuman's existing generic
/// storage-key KDF; mnemonic parsing and all chain derivation remain in the
/// confidential module operation.
pub async fn derive_recovery_material(
    ctx: &DispatchCtx,
    mnemonic: String,
) -> Result<Outcome<WalletRecoveryMaterial>, String> {
    let word_count = mnemonic.split_whitespace().count();
    if tinywallet_bus::validate_mnemonic_word_count_usize(word_count).is_err() {
        return Err(format!(
            "recovery phrase must contain one of {} words",
            supported_word_counts()
        ));
    }

    let config = ctx.load_config().await?;
    let mnemonic = Zeroizing::new(mnemonic);
    let mnemonic = Zeroizing::new(mnemonic.split_whitespace().collect::<Vec<_>>().join(" "));
    let seed = crate::modules::wallet::derive_mnemonic_seed(&config, mnemonic.to_string())
        .await
        .map_err(|error| error.to_string())?;
    let seed = Zeroizing::new(seed.seed);
    if seed.len() != 64 {
        return Err("wallet module returned an invalid BIP-39 seed length".to_string());
    }

    let plan = derivation_plan();
    let mut derived_accounts = Vec::with_capacity(plan.len());
    for planned in plan {
        let address =
            derive_address(&config, &mnemonic, planned.chain, &planned.derivation_path).await?;
        derived_accounts.push(WalletAccount { address, ..planned });
    }

    Ok(Outcome::new(
        WalletRecoveryMaterial {
            seed: seed.to_vec(),
            accounts: derived_accounts,
        },
        vec!["recovery phrase validated and wallet accounts derived".to_string()],
    ))
}

/// Every account recovery and import derive, address left blank: the primary
/// account of each chain in [`PRIMARY_ACCOUNTS`] order, then
/// [`SECONDARY_ACCOUNTS`].
pub(crate) fn derivation_plan() -> Vec<WalletAccount> {
    let primary = PRIMARY_ACCOUNTS.iter().map(|(chain, path)| WalletAccount {
        chain: *chain,
        address: String::new(),
        derivation_path: (*path).to_string(),
        index: 0,
        label: None,
    });
    let secondary = SECONDARY_ACCOUNTS.iter().map(|account| WalletAccount {
        chain: account.chain,
        address: String::new(),
        derivation_path: account.derivation_path.to_string(),
        index: account.index,
        label: Some(account.label.to_string()),
    });
    primary.chain(secondary).collect()
}

fn module_chain(chain: WalletChain) -> ModuleChain {
    match chain {
        WalletChain::Evm => ModuleChain::Evm,
        WalletChain::Btc => ModuleChain::Btc,
        WalletChain::Solana => ModuleChain::Solana,
        WalletChain::Tron => ModuleChain::Tron,
    }
}

/// Ask the module for the address at `derivation_path`.
async fn derive_address(
    config: &crate::config::Config,
    mnemonic: &str,
    chain: WalletChain,
    derivation_path: &str,
) -> Result<String, String> {
    let mut secret = SecretMaterial {
        mnemonic: mnemonic.to_string(),
        derivation_path: derivation_path.to_string(),
        chain: module_chain(chain),
    };
    let derived = crate::modules::wallet::derive_account(config, &secret).await;
    secret.mnemonic.zeroize();
    Ok(derived.map_err(|error| error.to_string())?.address)
}

/// Check whether a phrase is valid BIP-39 input without deriving account data.
pub async fn validate_recovery_phrase(
    ctx: &DispatchCtx,
    mnemonic: String,
) -> Result<Outcome<RecoveryPhraseValidation>, String> {
    use crate::modules::wallet::WalletCallError;

    let config = ctx.load_config().await?;
    let valid = match crate::modules::wallet::derive_mnemonic_seed(&config, mnemonic).await {
        Ok(mut response) => {
            if response.seed.len() != 64 {
                response.seed.zeroize();
                return Err("wallet module returned an invalid BIP-39 seed length".to_string());
            }
            response.seed.zeroize();
            true
        }
        Err(WalletCallError::InvalidInput(_)) => false,
        Err(error) => return Err(error.to_string()),
    };
    Ok(Outcome::new(
        RecoveryPhraseValidation { valid },
        vec!["recovery phrase checked by wallet module".to_string()],
    ))
}

fn validate_setup(params: &WalletSetupParams) -> Result<Vec<WalletAccount>, String> {
    if !params.consent_granted {
        return Err("wallet setup requires explicit consent".to_string());
    }
    if tinywallet_bus::validate_mnemonic_word_count(params.mnemonic_word_count).is_err() {
        return Err(format!(
            "unsupported mnemonic word count {}; expected one of {}",
            params.mnemonic_word_count,
            supported_word_counts()
        ));
    }
    if params
        .encrypted_mnemonic
        .as_ref()
        .map(|value| value.trim().is_empty())
        .unwrap_or(true)
    {
        return Err(
            "wallet setup requires encrypted mnemonic material for signing-enabled local wallets"
                .to_string(),
        );
    }

    let mut normalized = Vec::with_capacity(params.accounts.len());
    for account in &params.accounts {
        let address = account.address.trim();
        let derivation_path = account.derivation_path.trim();
        if address.is_empty() {
            return Err(format!(
                "wallet setup account '{}' is missing an address",
                account.chain.as_str()
            ));
        }
        if derivation_path.is_empty() {
            return Err(format!(
                "wallet setup account '{}' is missing a derivation path",
                account.chain.as_str()
            ));
        }
        if account.index == 0
            && SECONDARY_ACCOUNTS.iter().any(|secondary| {
                secondary.chain == account.chain && secondary.derivation_path == derivation_path
            })
        {
            // A primary at a secondary path resolves to that secondary account's
            // key, so the secondary's program policy would sign for the primary.
            return Err(format!(
                "wallet setup account '{}' index 0 uses a secondary account path; a primary account must not alias one",
                account.chain.as_str()
            ));
        }
        if account.index > 0 {
            // A secondary account must be one the host knows, at its canonical
            // path, so the key it later signs with is the one its policy names.
            let expected = account_derivation_path(account.chain, account.index);
            if expected != Some(derivation_path) {
                return Err(format!(
                    "wallet setup account '{}' index {} is not a known secondary account",
                    account.chain.as_str(),
                    account.index
                ));
            }
            if normalized.iter().any(|existing: &WalletAccount| {
                existing.chain == account.chain && existing.index == account.index
            }) {
                return Err(format!(
                    "wallet setup lists '{}' index {} more than once",
                    account.chain.as_str(),
                    account.index
                ));
            }
        }
        normalized.push(WalletAccount {
            chain: account.chain,
            address: address.to_string(),
            derivation_path: derivation_path.to_string(),
            index: account.index,
            label: account
                .label
                .as_ref()
                .map(|label| label.trim().to_string())
                .filter(|label| !label.is_empty()),
        });
    }

    for chain in WalletChain::ALL {
        let count = normalized
            .iter()
            .filter(|account| account.chain == chain && account.is_primary())
            .count();
        if count != 1 {
            return Err(format!(
                "wallet setup must include exactly one '{}' account",
                chain.as_str()
            ));
        }
    }

    Ok(normalized)
}

pub async fn status(ctx: &DispatchCtx) -> Result<Outcome<WalletStatus>, String> {
    let config = ctx.load_config().await?;
    let _guard = WALLET_STATE_FILE_LOCK.lock();
    let status = to_status(&config, load_stored_wallet_state_unlocked(&config)?);

    debug!(
        "{LOG_PREFIX} status configured={} onboarding_completed={} account_count={}",
        status.configured,
        status.onboarding_completed,
        status.accounts.len()
    );

    Ok(Outcome::new(
        status,
        vec!["wallet status fetched".to_string()],
    ))
}

pub async fn setup(
    ctx: &DispatchCtx,
    params: WalletSetupParams,
) -> Result<Outcome<WalletStatus>, String> {
    let config = ctx.load_config().await?;
    let accounts = validate_setup(&params)?;
    let encrypted_mnemonic = params
        .encrypted_mnemonic
        .as_ref()
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())
        .ok_or_else(|| {
            "wallet setup requires encrypted mnemonic material for signing-enabled local wallets"
                .to_string()
        })?;

    // ── Idempotency guard: reject overwrite unless caller explicitly set force=true ──
    // Acquire lock before the existence check so no TOCTOU race is possible.
    let _guard = WALLET_STATE_FILE_LOCK.lock();
    if let Some(_existing) = load_stored_wallet_state_unlocked(&config)? {
        if !params.force {
            debug!("{LOG_PREFIX} setup rejected: wallet already configured and force=false");
            return Err("wallet is already configured; pass force=true to overwrite".to_string());
        }
        debug!("{LOG_PREFIX} setup: overwriting existing wallet (force=true)");
    }

    let state = StoredWalletState {
        consent_granted: params.consent_granted,
        source: params.source,
        mnemonic_word_count: params.mnemonic_word_count,
        encrypted_mnemonic: Some(encrypted_mnemonic),
        accounts,
        updated_at_ms: state::current_time_ms(),
    };

    save_stored_wallet_state_unlocked(&config, &state)?;
    let status = to_status(&config, Some(state));

    debug!(
        "{LOG_PREFIX} setup saved source={:?} account_count={} mnemonic_words={} secret_stored={}",
        status.source,
        status.accounts.len(),
        status.mnemonic_word_count.unwrap_or_default(),
        status.secret_stored
    );

    Ok(Outcome::new(status, vec!["wallet setup saved".to_string()]))
}

/// Decrypt and return the stored recovery phrase for the current wallet.
///
/// This is a read-only operation — it never writes to disk or the keychain.
/// The plaintext phrase is returned only in the RPC response and must be kept
/// in transient React state on the frontend; it must never be logged or persisted.
pub async fn reveal_recovery_phrase(
    ctx: &DispatchCtx,
) -> Result<Outcome<RevealRecoveryPhraseResult>, String> {
    debug!("{LOG_PREFIX} reveal_recovery_phrase ENTRY");

    let config = ctx.load_config().await.map_err(|e| {
        log::warn!("{LOG_PREFIX} reveal_recovery_phrase config load failed: {e}");
        e
    })?;

    // Acquire the lock to load state, then drop it before any await point.
    // parking_lot::MutexGuard is not Send, so it must not be held across awaits.
    let ciphertext = {
        let _guard = WALLET_STATE_FILE_LOCK.lock();
        debug!("{LOG_PREFIX} reveal_recovery_phrase state lock acquired");

        let state = match load_stored_wallet_state_unlocked(&config)? {
            Some(s) => s,
            None => {
                debug!("{LOG_PREFIX} reveal_recovery_phrase no wallet state found");
                return Err(
                    "No recovery phrase is available to reveal. Set up or unlock your wallet first."
                        .to_string(),
                );
            }
        };

        // Primary path: mnemonic is in the state returned by load (either from
        // the JSON field or merged in from the OS keychain by
        // load_stored_wallet_state_unlocked).  Fallback: probe the keychain
        // directly in case the mnemonic is stored there but was not merged into
        // `state` (e.g. headless / CI keychain that was transiently unavailable
        // during the initial probe inside load_stored_wallet_state_unlocked, or
        // any environment where the mnemonic lives only in the keychain).
        let enc_mnemonic_opt = state
            .encrypted_mnemonic
            .as_ref()
            .map(|v| v.trim().to_string())
            .filter(|v| !v.is_empty())
            .or_else(|| {
                debug!(
                    "{LOG_PREFIX} reveal_recovery_phrase: mnemonic absent from state, \
                     falling back to direct keychain probe"
                );
                keychain_load_mnemonic(&config)
                    .map(|v| v.trim().to_string())
                    .filter(|v| !v.is_empty())
            });

        enc_mnemonic_opt.ok_or_else(|| {
            debug!("{LOG_PREFIX} reveal_recovery_phrase encrypted mnemonic missing from state");
            "No recovery phrase is available to reveal. Set up or unlock your wallet first."
                .to_string()
        })?
        // _guard dropped here — before the decrypt await below
    };

    debug!("{LOG_PREFIX} reveal_recovery_phrase decrypting mnemonic");

    let phrase = crate::credentials::ops::decrypt_secret(&config, &ciphertext)
        .await
        .map_err(|e| {
            log::warn!("{LOG_PREFIX} reveal_recovery_phrase decrypt failed: {e}");
            format!("Failed to decrypt recovery phrase: {e}")
        })?
        .value;

    let word_count = phrase.split_whitespace().count();

    debug!(
        "{LOG_PREFIX} reveal_recovery_phrase OK word_count={}",
        word_count
    );

    Ok(Outcome::new(
        RevealRecoveryPhraseResult { phrase, word_count },
        vec!["recovery phrase revealed".to_string()],
    ))
}

/// The encrypted phrase and the derivation path of `chain`'s account `index`.
///
/// A secondary account missing from state written before it existed resolves
/// to its canonical path ([`SECONDARY_ACCOUNTS`]), so signing never needs the
/// address to have been stored first.
pub(crate) async fn secret_material(
    ctx: &DispatchCtx,
    chain: WalletChain,
    index: u32,
) -> Result<WalletSecretMaterial, String> {
    debug!(
        "{LOG_PREFIX} secret_material loading config chain={}",
        chain.as_str()
    );
    let config = ctx.load_config().await?;
    debug!(
        "{LOG_PREFIX} secret_material acquiring state lock chain={}",
        chain.as_str()
    );
    let _guard = WALLET_STATE_FILE_LOCK.lock();
    let state = match load_stored_wallet_state_unlocked(&config)? {
        Some(state) => state,
        None => {
            debug!(
                "{LOG_PREFIX} secret_material missing wallet state chain={}",
                chain.as_str()
            );
            return Err(WALLET_NOT_CONFIGURED_MESSAGE.to_string());
        }
    };
    let encrypted_mnemonic = state
        .encrypted_mnemonic
        .as_ref()
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())
        .ok_or_else(|| {
            debug!(
                "{LOG_PREFIX} secret_material missing encrypted mnemonic chain={}",
                chain.as_str()
            );
            "wallet secret material is missing; re-import the recovery phrase to enable signing"
                .to_string()
        })?;
    let derivation_path = state
        .accounts
        .iter()
        .find(|account| account.chain == chain && account.index == index)
        .map(|account| account.derivation_path.clone())
        .or_else(|| {
            (index > 0)
                .then(|| secondary_account(chain, index))
                .flatten()
                .map(|account| account.derivation_path.to_string())
        })
        .ok_or_else(|| {
            debug!(
                "{LOG_PREFIX} secret_material missing account chain={} index={index}",
                chain.as_str()
            );
            if index == 0 {
                format!("no wallet account derived for chain '{}'", chain.as_str())
            } else {
                format!(
                    "no wallet account derived for chain '{}' index {index}",
                    chain.as_str()
                )
            }
        })?;
    debug!(
        "{LOG_PREFIX} secret_material loaded chain={} index={index} derivation_path={}",
        chain.as_str(),
        derivation_path
    );
    Ok(WalletSecretMaterial {
        encrypted_mnemonic,
        derivation_path,
    })
}

/// The stored account `index` of `chain`, deriving and storing it first when
/// it is a known secondary account that this wallet's state predates.
///
/// This is the migration path for wallets imported before a secondary account
/// existed: the encrypted phrase is decrypted, the module derives the address,
/// and the account is added to the stored state.
pub async fn ensure_account(
    ctx: &DispatchCtx,
    chain: WalletChain,
    index: u32,
) -> Result<WalletAccount, String> {
    let config = ctx.load_config().await?;
    let encrypted_mnemonic = {
        let _guard = WALLET_STATE_FILE_LOCK.lock();
        let state = load_stored_wallet_state_unlocked(&config)?
            .ok_or_else(|| WALLET_NOT_CONFIGURED_MESSAGE.to_string())?;
        if let Some(account) = state
            .accounts
            .iter()
            .find(|account| account.chain == chain && account.index == index)
        {
            return Ok(account.clone());
        }
        if index == 0 || secondary_account(chain, index).is_none() {
            return Err(format!(
                "no wallet account '{}' index {index}; secondary accounts are: {}",
                chain.as_str(),
                SECONDARY_ACCOUNTS
                    .iter()
                    .map(|account| format!("{} index {}", account.chain.as_str(), account.index))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        state
            .encrypted_mnemonic
            .as_ref()
            .map(|value| value.trim().to_string())
            .filter(|value| !value.is_empty())
            .or_else(|| keychain_load_mnemonic(&config))
            .ok_or_else(|| {
                "wallet secret material is missing; re-import the recovery phrase to enable signing"
                    .to_string()
            })?
    };
    let Some(planned) = derivation_plan()
        .into_iter()
        .find(|account| account.chain == chain && account.index == index)
    else {
        return Err(format!(
            "no derivation for '{}' index {index}",
            chain.as_str()
        ));
    };
    let mnemonic = Zeroizing::new(
        crate::credentials::ops::decrypt_secret(&config, &encrypted_mnemonic)
            .await
            .map_err(|error| format!("failed to decrypt the recovery phrase: {error}"))?
            .value,
    );
    let address = derive_address(&config, &mnemonic, chain, &planned.derivation_path).await?;
    let account = WalletAccount { address, ..planned };

    let _guard = WALLET_STATE_FILE_LOCK.lock();
    let mut state = load_stored_wallet_state_unlocked(&config)?
        .ok_or_else(|| WALLET_NOT_CONFIGURED_MESSAGE.to_string())?;
    if state.encrypted_mnemonic.is_some()
        && state.encrypted_mnemonic.as_deref().map(str::trim) != Some(encrypted_mnemonic.as_str())
    {
        return Err("the wallet changed while its account was being derived; retry".to_string());
    }
    if let Some(existing) = state
        .accounts
        .iter()
        .find(|existing| existing.chain == chain && existing.index == index)
    {
        return Ok(existing.clone());
    }
    state.accounts.push(account.clone());
    state.updated_at_ms = state::current_time_ms();
    save_stored_wallet_state_unlocked(&config, &state)?;
    debug!(
        "{LOG_PREFIX} ensure_account stored chain={} index={index}",
        chain.as_str()
    );
    Ok(account)
}

