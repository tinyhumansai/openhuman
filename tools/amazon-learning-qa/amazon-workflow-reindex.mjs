#!/usr/bin/env node

import { readFile, readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { execFile } from "node:child_process";
import path from "node:path";
import { promisify } from "node:util";

import { buildOpenHumanMemoryDocument, normalizeStoredDossier } from "./amazon-dossier-lib.mjs";
import { resolveAmazonQaPaths } from "./amazon-qa-paths.mjs";

const QA_PATHS = resolveAmazonQaPaths(import.meta.dirname);
const WORKSPACE = QA_PATHS.workspace;
const DB_PATH = QA_PATHS.memoryDbPath;
const DEFAULT_NAMESPACE = "amazon-learning";
const DEFAULT_RPC_URL = "http://127.0.0.1:7789/rpc";
const DEFAULT_TOKEN = "openhuman-amazon-local-token";

const execFileAsync = promisify(execFile);

function argValue(args, name, fallback = undefined) {
  const index = args.indexOf(name);
  if (index === -1) return fallback;
  const value = args[index + 1];
  if (!value || value.startsWith("--")) throw new Error(`Missing value for ${name}`);
  return value;
}

function usage() {
  console.log(`Usage:
  node tools/amazon-workflow-reindex.mjs [--namespace ${DEFAULT_NAMESPACE}] [--rpc-url ${DEFAULT_RPC_URL}]

Rewrites saved Amazon learning dossiers into the OpenHuman workflow memory namespace
so their semantic vectors are regenerated by the current core embedding provider.`);
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes("--help") || args.includes("-h")) {
    usage();
    return;
  }

  const namespace = argValue(args, "--namespace", process.env.OPENHUMAN_NAMESPACE || DEFAULT_NAMESPACE);
  const rpcUrl = argValue(args, "--rpc-url", process.env.OPENHUMAN_RPC_URL || DEFAULT_RPC_URL);
  const token = process.env.OPENHUMAN_CORE_TOKEN || DEFAULT_TOKEN;
  const archiveDir = path.join(WORKSPACE, "learning-archives", safeNamespace(namespace));
  const files = existsSync(archiveDir)
    ? (await readdir(archiveDir)).filter((name) => name.endsWith(".json")).sort()
    : [];

  const results = [];
  for (const file of files) {
    const filePath = path.join(archiveDir, file);
    const dossier = normalizeStoredDossier(JSON.parse(await readFile(filePath, "utf8")));
    const memoryDoc = buildOpenHumanMemoryDocument(dossier, { sourceNamespace: namespace });
    if (memoryDoc.namespace === namespace) {
      throw new Error(`Refusing to write workflow dossier into source namespace: ${namespace}`);
    }

    try {
      const result = await rpcCall(rpcUrl, token, "openhuman.memory_doc_put", memoryDoc);
      const documentId = openHumanDocumentIdFromResult(result);
      const indexState = await getMemoryDocumentIndexState(memoryDoc.namespace, documentId);
      const status = indexState.indexStatus === "indexed" ? "synced" : "pending";
      const updated = normalizeStoredDossier({
        ...dossier,
        openhumanMemory: {
          namespace: memoryDoc.namespace,
          key: memoryDoc.key,
          documentTitle: memoryDoc.title,
          syncedAt: new Date().toISOString(),
          status,
          documentId,
          ...indexState,
          error: "",
        },
      });
      await writeFile(filePath, `${JSON.stringify(updated, null, 2)}\n`, "utf8");
      results.push({
        id: updated.id,
        file,
        status,
        indexStatus: indexState.indexStatus,
        indexedChunks: indexState.indexedChunks,
        totalChunks: indexState.totalChunks,
        documentId,
      });
    } catch (error) {
      const updated = normalizeStoredDossier({
        ...dossier,
        openhumanMemory: {
          namespace: memoryDoc.namespace,
          key: memoryDoc.key,
          documentTitle: memoryDoc.title,
          syncedAt: new Date().toISOString(),
          status: "failed",
          documentId: dossier.openhumanMemory?.documentId || "",
          error: friendlyError(error),
        },
      });
      await writeFile(filePath, `${JSON.stringify(updated, null, 2)}\n`, "utf8");
      results.push({ id: updated.id, file, status: "failed", error: friendlyError(error) });
    }
  }

  const indexed = results.filter((item) => item.status === "synced").length;
  const pending = results.filter((item) => item.status === "pending").length;
  const failed = results.filter((item) => item.status === "failed").length;
  console.log(JSON.stringify({ namespace, files: files.length, indexed, pending, failed, results }, null, 2));
}

async function rpcCall(rpcUrl, token, method, params) {
  const response = await fetch(rpcUrl, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      authorization: `Bearer ${token}`,
    },
    body: JSON.stringify({ jsonrpc: "2.0", id: Date.now(), method, params }),
  });
  const payload = await response.json();
  const envelopeError = payload.error ?? payload.result?.error;
  if (!response.ok || envelopeError) {
    throw new Error(`${method} failed: ${JSON.stringify(envelopeError ?? payload)}`);
  }
  return payload.result;
}

function openHumanDocumentIdFromResult(result) {
  return result?.result?.document_id ||
    result?.result?.documentId ||
    result?.document_id ||
    result?.documentId ||
    result?.id ||
    "";
}

async function getMemoryDocumentIndexState(namespace, documentId) {
  if (!existsSync(DB_PATH) || !documentId) {
    return { indexStatus: "unknown", totalChunks: 0, indexedChunks: 0 };
  }
  const ns = quoteSql(namespace);
  const doc = quoteSql(documentId);
  const sql = [
    "select",
    `(select count(*) from vector_chunks where namespace='${ns}' and document_id='${doc}') || '|' ||`,
    `(select count(*) from vector_chunks where namespace='${ns}' and document_id='${doc}' and embedding is not null and length(embedding)>0);`,
  ].join(" ");
  try {
    const { stdout } = await execFileAsync("sqlite3", [DB_PATH, sql], { timeout: 3000 });
    const [totalChunks, indexedChunks] = stdout
      .trim()
      .split("|")
      .map((value) => Number(value || 0));
    const indexStatus = totalChunks > 0 && indexedChunks >= totalChunks ? "indexed" : "missing_embeddings";
    return { indexStatus, totalChunks, indexedChunks };
  } catch {
    return { indexStatus: "unknown", totalChunks: 0, indexedChunks: 0 };
  }
}

function quoteSql(value) {
  return String(value || "").replaceAll("'", "''");
}

function safeNamespace(namespace) {
  return String(namespace || DEFAULT_NAMESPACE).replace(/[^a-zA-Z0-9_-]/g, "_");
}

function friendlyError(error) {
  return error instanceof Error ? error.message : String(error);
}

main().catch((error) => {
  console.error(friendlyError(error));
  process.exit(1);
});
